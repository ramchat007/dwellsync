export function getPermissionsForRole(role: RoleId | null | undefined): string[] {
  if (!role) return [];
  return ROLE_PERMISSIONS_MAP[role] || [];
}

export function roleHasPermission(role: RoleId | null | undefined, permission: string): boolean {
  if (!role) return false;
  const permissions = getPermissionsForRole(role);
  return permissions.includes(permission);
}
